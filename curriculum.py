def _monday_on_or_before(d: date) -> date:
    return d - timedelta(days=d.weekday())


def week_number_for_date(target: date, camp_start: date) -> int:
    start_monday = _monday_on_or_before(camp_start)
    target_monday = _monday_on_or_before(target)
    diff_weeks = (target_monday - start_monday).days // 7
    return max(1, diff_weeks + 1)


def _parse(date_str: str) -> date:
    return datetime.strptime(date_str, "%Y-%m-%d").date()


def topics_for_week(week_num: int, camp_start: date) -> str:
    topics = []
    for date_str, _day, _subject, content in SCHEDULE:
        d = _parse(date_str)
        if week_number_for_date(d, camp_start) == week_num and content not in topics:
            topics.append(content)
    return ", ".join(topics) if topics else ""


def suggested_week_number(today: date, camp_start: date) -> int:
    return week_number_for_date(today, camp_start)
